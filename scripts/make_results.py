"""Regenerate docs/RESULTS.md from results/*.json and ckpt/*/meta.json. Never edit RESULTS.md by hand."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAMES = {
    "expert": "Scripted expert (reference, same perception)",
    "bc": "MLP behavior cloning",
    "act": "ACT (LeRobot)",
    "dp": "Diffusion Policy (LeRobot)",
    "dp_noft": "Diffusion Policy without wrist F/T",
    "bc_noft": "MLP behavior cloning without wrist F/T",
    "dp_na2": "Diffusion Policy, re-plan every 2 actions",
    "act_na1": "ACT, re-plan every action",
}


def episodes(policy, off):
    p = ROOT / "results" / f"{policy}_off{off:.1f}.json"
    return {e["seed"]: e["success"] for e in json.loads(p.read_text())["episodes"]} if p.exists() else None


def mcnemar(a, b):
    """Exact two-sided McNemar test on paired episodes (same seeds)."""
    from math import comb

    seeds = sorted(set(a) & set(b))
    n01 = sum(a[s] and not b[s] for s in seeds)
    n10 = sum(b[s] and not a[s] for s in seeds)
    n = n01 + n10
    k = min(n01, n10)
    p = min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) / 2**n) if n else 1.0
    return n01, n10, p


def load(policy, off):
    p = ROOT / "results" / f"{policy}_off{off:.1f}.json"
    return json.loads(p.read_text())["summary"] if p.exists() else None


def cell(s):
    if not s:
        return "not run"
    return f"{s['success']}/{s['n']} ({100 * s['success_rate']:.1f}%, CI {100 * s['ci95'][0]:.1f}-{100 * s['ci95'][1]:.1f})"


def main():
    demo = json.loads((ROOT / "data" / "demos_meta.json").read_text())
    lines = [
        "# Results",
        "",
        "Generated by `scripts/make_results.py` from `results/*.json`. Simulation only (MuJoCo, Franka Panda model",
        "from MuJoCo Menagerie); no real robot was used. Evaluation seeds start at 100000 and never overlap the",
        "demonstration seeds (0-499). 95% intervals are Wilson score intervals.",
        "",
        "## Demonstrations",
        "",
        f"- {demo['episodes_kept']} of {demo['episodes_run']} scripted episodes kept (successful only), "
        f"{demo['frames']:,} frames at 20 Hz; {demo['kept_with_recovery']} kept episodes contain a force-guided recovery.",
        f"- Source: {demo['source']}.",
        "",
        "## Insertion success (1 mm clearance per side, 2 mm chamfer)",
        "",
        "| Policy | Nominal perception | Fixture perceived 2 mm off | Final xy error, median (nominal) | Peak contact force, median (nominal) |",
        "|---|---|---|---|---|",
    ]
    for k in ["expert", "bc", "bc_noft", "act", "act_na1", "dp", "dp_na2", "dp_noft"]:
        a, b = load(k, 0.0), load(k, 2.0)
        if not a and not b:
            continue
        err = f"{a['err_xy_mm_median']:.2f} mm" if a and a["err_xy_mm_median"] is not None else "-"
        f = f"{a['peak_force_median_N']:.1f} N" if a else "-"
        lines.append(f"| {NAMES[k]} | {cell(a)} | {cell(b)} | {err} | {f} |")
    lines += [
        "",
        "## Training",
        "",
        "| Policy | Parameters | Steps | Batch | Train time | Device |",
        "|---|---|---|---|---|---|",
    ]
    for k in ["bc", "bc_noft", "act", "dp", "dp_noft"]:
        p = ROOT / "ckpt" / k / "meta.json"
        if p.exists():
            m = json.loads(p.read_text())
            lines.append(
                f"| {NAMES[k]} | {m['params']:,} | {m['steps']:,} | {m['batch']} | {m['train_seconds'] / 60:.1f} min | {m['device']} |"
            )
    lines += [
        "",
        "## Does the wrist force-torque input matter? (paired, same 200 seeds, exact McNemar)",
        "",
        "| Comparison | Condition | Only with F/T succeeded | Only without F/T succeeded | p |",
        "|---|---|---|---|---|",
    ]
    for a_, b_ in [("bc", "bc_noft"), ("dp", "dp_noft")]:
        for off in (0.0, 2.0):
            A, B = episodes(a_, off), episodes(b_, off)
            if A and B:
                n01, n10, p = mcnemar(A, B)
                cond = "nominal" if off == 0 else "2 mm perception error"
                lines.append(f"| {NAMES[a_]} vs without F/T | {cond} | {n01} | {n10} | {p:.1e} |")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
